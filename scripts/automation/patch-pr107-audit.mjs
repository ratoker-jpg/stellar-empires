import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const root = process.cwd();
const resolve = (relativePath) => path.join(root, relativePath);
const write = async (relativePath, content) => {
  const target = resolve(relativePath);
  await mkdir(path.dirname(target), { recursive: true });
  await writeFile(target, content);
};

const configPath = resolve('assets/manifests/asset-pipeline.config.json');
const config = JSON.parse(await readFile(configPath, 'utf8'));
config.universeSourceRoot = 'assets/source/universe-navigation';
config.spaceMapTypeScriptManifestPath =
  'src/assets/generated/spaceMapAssetManifest.generated.ts';
config.spaceMapQaRoot = 'docs/assets/qa/universe';
config.spaceMapQaContactSheetCount = 18;
config.spaceMapBudgets = {
  ...config.spaceMapBudgets,
  totalTransferBytes: config.spaceMapBudgets.transferBytes,
  totalDecodedBytes: config.spaceMapBudgets.decodedBytes,
  minimumTransparentMarginRatio: 0.03,
  viewDecodedBytes: {
    universe: config.spaceMapBudgets.universeViewDecodedBytes,
    galaxy: config.spaceMapBudgets.galaxyViewDecodedBytes,
    'solar-system': config.spaceMapBudgets.solarSystemViewDecodedBytes,
  },
};
await writeFile(configPath, `${JSON.stringify(config, null, 2)}\n`);

await write('scripts/assets/audit.mjs', `import {
  buildAuditManifest,
  formatBytes,
  loadConfig,
  loadJson,
  writeStableJson,
  writeText,
} from './lib.mjs';

function markdownReport(manifest, config, spaceMapBindings) {
  const classifications = Object.entries(manifest.summary.byClassification)
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([classification, count]) => \`| \${classification} | \${count} |\`)
    .join('\\n');
  const families = Object.entries(manifest.summary.byFamily)
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([family, count]) => \`| \${family} | \${count} |\`)
    .join('\\n');
  const universe = manifest.assets.filter((asset) => asset.classification === 'source-intake');
  const universeRuntime = manifest.assets.filter((asset) =>
    asset.path.startsWith('public/assets/generated/universe/'),
  );
  const newAssets = manifest.assets.filter((asset) => asset.path.startsWith('assets/source/New assets/'));
  const oversizedUniverse = universe
    .filter((asset) => {
      if (asset.width === null || asset.height === null) return false;
      if (asset.family === 'universe-galaxy' || asset.family === 'universe-planet') {
        return asset.width > 256 || asset.height > 256;
      }
      if (asset.family === 'universe-system-star') return asset.width > 128 || asset.height > 128;
      if (asset.family === 'universe-sun') return asset.width > 512 || asset.height > 512;
      return asset.width > 256 || asset.height > 256;
    })
    .slice(0, 30);
  const runtimeById = new Map(
    universeRuntime
      .filter((asset) => asset.semanticId !== null)
      .map((asset) => [asset.semanticId, asset]),
  );
  const decodedFor = (entries) => entries.reduce(
    (sum, entry) => sum + (runtimeById.get(entry.runtimeSemanticId)?.decodedBytes ?? 0),
    0,
  );
  const universeView = decodedFor(
    spaceMapBindings.entries.filter((entry) => entry.viewGroup === 'universe'),
  );
  const galaxyView = decodedFor(
    spaceMapBindings.entries.filter((entry) => entry.viewGroup === 'galaxy'),
  );
  const solarEntries = spaceMapBindings.entries.filter(
    (entry) => entry.viewGroup === 'solar-system',
  );
  const sunDetails = solarEntries.filter((entry) => entry.family === 'sun-detail');
  const solarFixed = solarEntries.filter((entry) => entry.family !== 'sun-detail');
  const solarView =
    decodedFor(solarFixed) +
    Math.max(...sunDetails.map((entry) =>
      runtimeById.get(entry.runtimeSemanticId)?.decodedBytes ?? 0
    ));
  const universeBytes = universeRuntime.reduce((sum, asset) => sum + asset.bytes, 0);
  const universeDecoded = universeRuntime.reduce(
    (sum, asset) => sum + (asset.decodedBytes ?? 0),
    0,
  );

  return \`# Generated asset audit\\n\\n\` +
    \`This file is generated by \\\`npm run assets:audit\\\`. Do not edit it manually.\\n\\n\` +
    \`## Totals\\n\\n\` +
    \`- audited files: **\${manifest.summary.totalFiles}**\\n\` +
    \`- source library files under \\\`assets/source/New assets\\\`: **\${newAssets.length}**\\n\` +
    \`- Universe source files: **\${universe.length}**\\n\` +
    \`- Universe runtime derivatives: **\${universeRuntime.length}**\\n\` +
    \`- audited transfer bytes: **\${formatBytes(manifest.summary.totalBytes)}**\\n\` +
    \`- estimated decoded RGBA bytes: **\${formatBytes(manifest.summary.totalDecodedBytes)}**\\n\\n\` +
    \`## Universe runtime measurements\\n\\n\` +
    \`| Measurement | Actual | Gate |\\n|---|---:|---:|\\n\` +
    \`| Complete derivative transfer | \${formatBytes(universeBytes)} | \${formatBytes(config.spaceMapBudgets.transferBytes)} |\\n\` +
    \`| Complete derivative decoded RGBA | \${formatBytes(universeDecoded)} | \${formatBytes(config.spaceMapBudgets.decodedBytes)} |\\n\` +
    \`| Universe active-view decoded | \${formatBytes(universeView)} | \${formatBytes(config.spaceMapBudgets.universeViewDecodedBytes)} |\\n\` +
    \`| Galaxy active-view decoded | \${formatBytes(galaxyView)} | \${formatBytes(config.spaceMapBudgets.galaxyViewDecodedBytes)} |\\n\` +
    \`| Solar-system active-view decoded | \${formatBytes(solarView)} | \${formatBytes(config.spaceMapBudgets.solarSystemViewDecodedBytes)} |\\n\\n\` +
    \`## Classification\\n\\n| Classification | Files |\\n|---|---:|\\n\${classifications}\\n\\n\` +
    \`## Families\\n\\n| Family | Files |\\n|---|---:|\\n\${families}\\n\\n\` +
    \`## Universe source masters above runtime size\\n\\n\` +
    (oversizedUniverse.length === 0
      ? \`No oversized Universe source files were detected.\\n\`
      : \`| Path | Dimensions | Bytes | Semantic ID |\\n|---|---:|---:|---|\\n\${oversizedUniverse
          .map((asset) => \`| \\\`\${asset.path}\\\` | \${asset.width}×\${asset.height} | \${formatBytes(asset.bytes)} | \\\`\${asset.semanticId ?? 'unassigned'}\\\` |\`)
          .join('\\n')}\\n\`) +
    \`\\n## Reproduction\\n\\n\` +
    \`\\\`npm run assets:audit\\\` rebuilds the JSON manifest and this report. \` +
    \`\\\`npm run assets:check\\\` fails when committed output differs from a clean audit.\\n\`;
}

const config = await loadConfig();
const manifest = await buildAuditManifest(config);
const spaceMapBindings = await loadJson(config.spaceMapBindingsPath);
await writeStableJson(config.auditManifestPath, manifest);
await writeText(config.auditReportPath, markdownReport(manifest, config, spaceMapBindings));
console.log(\`Audited \${manifest.summary.totalFiles} asset files.\`);
`);

