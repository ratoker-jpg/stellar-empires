import { buildAuditManifest, formatBytes, loadConfig, writeStableJson, writeText } from './lib.mjs';

function markdownReport(manifest) {
  const classifications = Object.entries(manifest.summary.byClassification)
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([classification, count]) => `| ${classification} | ${count} |`)
    .join('\n');
  const families = Object.entries(manifest.summary.byFamily)
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([family, count]) => `| ${family} | ${count} |`)
    .join('\n');
  const universe = manifest.assets.filter((asset) => asset.path.startsWith('assets/source/universe-navigation/'));
  const universeRuntime = manifest.assets.filter((asset) => asset.path.startsWith('public/assets/generated/universe/'));
  const newAssets = manifest.assets.filter((asset) => asset.path.startsWith('assets/source/New assets/'));
  const oversizedUniverse = universe
    .filter((asset) => {
      if (asset.width === null || asset.height === null) return false;
      if (asset.family === 'universe-galaxy' || asset.family === 'universe-planet') {
        return asset.width > 256 || asset.height > 256;
      }
      if (asset.family === 'universe-system-star') return asset.width > 128 || asset.height > 128;
      if (asset.family === 'universe-sun') return asset.width > 512 || asset.height > 512;
      return asset.width > 256 || asset.height > 256;
    })
    .slice(0, 30);

  return `# Generated asset audit\n\n` +
    `This file is generated by \`npm run assets:audit\`. Do not edit it manually.\n\n` +
    `## Totals\n\n` +
    `- audited files: **${manifest.summary.totalFiles}**\n` +
    `- source library files under \`assets/source/New assets\`: **${newAssets.length}**\n` +
    `- Universe source files: **${universe.length}**\n` +
    `- Universe runtime derivatives: **${universeRuntime.length}**\n` +
    `- audited transfer bytes: **${formatBytes(manifest.summary.totalBytes)}**\n` +
    `- estimated decoded RGBA bytes: **${formatBytes(manifest.summary.totalDecodedBytes)}**\n\n` +
    `## Classification\n\n| Classification | Files |\n|---|---:|\n${classifications}\n\n` +
    `## Families\n\n| Family | Files |\n|---|---:|\n${families}\n\n` +
    `## Universe source masters above runtime size\n\n` +
    (oversizedUniverse.length === 0
      ? `No oversized Universe source masters were detected.\n`
      : `| Path | Dimensions | Bytes | Semantic ID |\n|---|---:|---:|---|\n${oversizedUniverse
          .map((asset) => `| \`${asset.path}\` | ${asset.width}×${asset.height} | ${formatBytes(asset.bytes)} | \`${asset.semanticId ?? 'unassigned'}\` |`)
          .join('\n')}\n`) +
    `\n## Reproduction\n\n` +
    `\`npm run assets:audit\` rebuilds the JSON manifest and this report. ` +
    `\`npm run assets:check\` fails when committed output differs from a clean audit.\n`;
}

const config = await loadConfig();
const manifest = await buildAuditManifest(config);
await writeStableJson(config.auditManifestPath, manifest);
await writeText(config.auditReportPath, markdownReport(manifest));
console.log(`Audited ${manifest.summary.totalFiles} asset files.`);
